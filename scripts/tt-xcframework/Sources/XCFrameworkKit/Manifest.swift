// Reads the fork and upstream manifests and renders the distribution Package.swift.

import Foundation

public struct ManifestError: Error, CustomStringConvertible {
    public let description: String

    init(_ description: String) { self.description = description }
}

/// A prebuilt dependency the distribution package downloads as-is (WebRTC, UniFFI).
public struct BinaryDep: Codable, Equatable, Sendable {
    public let url: String
    public let checksum: String

    public init(url: String, checksum: String) {
        self.url = url
        self.checksum = checksum
    }
}

/// Where the distribution package finds LiveKit.xcframework.zip.
public enum BinarySource: Sendable {
    /// Release asset; the private repo uses the api.github.com asset URL, the public one the download URL.
    case url(String, checksum: String)
    /// Local zip next to Package.swift, for smoke tests.
    case path(String)
}

/// Written next to the zip by `build` and committed to both distribution repos, so the public
/// sync can render its manifest without rebuilding.
public struct BuildInfo: Codable, Equatable, Sendable {
    public let version: String
    public let checksum: String
    public let webrtc: BinaryDep
    public let uniffi: BinaryDep
    /// The WebRTC tag the fork pins; the public sync copies that release to the public WebRTC repo.
    /// nil in build-info.json of 2.15.2-a12 and earlier.
    public let webrtcVersion: String?

    public init(version: String, checksum: String, webrtc: BinaryDep, uniffi: BinaryDep, webrtcVersion: String?) {
        self.version = version
        self.checksum = checksum
        self.webrtc = webrtc
        self.uniffi = uniffi
        self.webrtcVersion = webrtcVersion
    }
}

/// The three binary sources of a distribution Package.swift. `webrtcURL` replaces the WebRTC URL
/// (the public repo points at the public WebRTC copy); the checksum stays the one in build-info.
public func manifestSources(info: BuildInfo, liveKitURL: String, webrtcURL: String?) -> (BinarySource, BinaryDep, BinaryDep) {
    let webrtc = webrtcURL.map { BinaryDep(url: $0, checksum: info.webrtc.checksum) } ?? info.webrtc
    return (.url(liveKitURL, checksum: info.checksum), webrtc, info.uniffi)
}

/// `.package(url: "...", exact|from: "...")` for the dependency whose line contains `pattern`.
public func forkDependency(_ pattern: String, in manifest: String) throws -> (url: String, version: String) {
    for line in manifest.components(separatedBy: .newlines) where line.contains(".package(") && line.contains(pattern) {
        if let url = line.firstMatch(of: #/url:\s*"(?<u>[^"]+)"/#),
           let version = line.firstMatch(of: #/(exact|from):\s*"(?<v>[^"]+)"/#)
        {
            return (String(url.u), String(version.v))
        }
    }
    throw ManifestError("\(pattern) not found in Package.swift")
}

/// The first binaryTarget's zip URL and checksum in a resolved upstream checkout's Package.swift.
public func binaryDep(fromCheckoutManifest manifest: String) throws -> BinaryDep {
    guard let url = manifest.firstMatch(of: #/url:\s*"(?<u>https://[^"]+\.zip)"/#),
          let checksum = manifest.firstMatch(of: #/checksum:\s*"(?<c>[0-9a-f]{64})"/#)
    else { throw ManifestError("binaryTarget url/checksum not found") }
    return BinaryDep(url: String(url.u), checksum: String(checksum.c))
}

/// `LiveKitSDK.version` from Sources/LiveKit/LiveKit.swift.
public func sdkVersion(fromLiveKitSwift source: String) throws -> String {
    guard let match = source.firstMatch(of: #/public static let version = "(?<v>[^"]+)"/#) else {
        throw ManifestError("LiveKitSDK.version not found")
    }
    return String(match.v)
}

public func renderManifest(liveKit: BinarySource, webrtc: BinaryDep, uniffi: BinaryDep) -> String {
    let liveKitTarget = switch liveKit {
    case let .url(url, checksum):
        """
                .binaryTarget(
                    name: "LiveKit",
                    url: "\(url)",
                    checksum: "\(checksum)"
                ),
        """
    case let .path(path):
        """
                .binaryTarget(name: "LiveKit", path: "\(path)"),
        """
    }
    return """
    // swift-tools-version:5.9
    // Generated by scripts/tt-xcframework in difftim/client-sdk-swift. Do not edit.

    import PackageDescription

    let package = Package(
        name: "LiveKit",
        platforms: [.iOS(.v15)],
        products: [
            .library(name: "LiveKit", targets: ["LiveKit", "LiveKitWebRTC", "RustLiveKitUniFFI"]),
        ],
        targets: [
    \(liveKitTarget)
            .binaryTarget(
                name: "LiveKitWebRTC",
                url: "\(webrtc.url)",
                checksum: "\(webrtc.checksum)"
            ),
            .binaryTarget(
                name: "RustLiveKitUniFFI",
                url: "\(uniffi.url)",
                checksum: "\(uniffi.checksum)"
            ),
        ]
    )

    """
}

/// Package.swift of the WebRTC distribution repos. The fork depends on this package from source,
/// so the platforms match the 3th1UOYgUtJkurSZ/webrtc-xcframework manifest it replaces.
public func renderWebRTCManifest(url: String, checksum: String) -> String {
    """
    // swift-tools-version:5.9
    // Generated by scripts/tt-xcframework in difftim/client-sdk-swift. Do not edit.

    import PackageDescription

    let package = Package(
        name: "LiveKitWebRTC",
        platforms: [.iOS(.v13), .macOS(.v10_15), .macCatalyst(.v14)],
        products: [
            .library(name: "LiveKitWebRTC", targets: ["LiveKitWebRTC"]),
        ],
        targets: [
            .binaryTarget(
                name: "LiveKitWebRTC",
                url: "\(url)",
                checksum: "\(checksum)"
            ),
        ]
    )

    """
}
